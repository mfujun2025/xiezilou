def build_article_html(tag_color, tag, intro, sections):
    sec_html = ''
    for sec_title, sec_content in sections:
        sec_html += f'<h2 class="text-2xl font-bold mt-8 mb-4 text-gray-900">{sec_title}</h2>\n'
        for para in sec_content.strip().split('\n'):
            para = para.strip()
            if para:
                sec_html += f'<p class="mb-4 text-gray-700 leading-relaxed">{para}</p>\n'

    faq_html = '''
      <h2 class="text-2xl font-bold mt-8 mb-4">常见问题解答</h2>
      <div class="space-y-4">
        <div class="bg-white rounded-lg p-4 shadow-sm">
          <h3 class="font-semibold text-gray-900 mb-2">上海写字楼租金一般多少？</h3>
          <p class="text-gray-600 text-sm">租金因区域、档次、配套等因素差异较大。北郊片区（宝山、嘉定、杨浦）日均2.5-4.5元/平米，市中心区域在8-15元/平米。</p>
        </div>
        <div class="bg-white rounded-lg p-4 shadow-sm">
          <h3 class="font-semibold text-gray-900 mb-2">如何选择合适的办公空间？</h3>
          <p class="text-gray-600 text-sm">建议从交通便利性、租金成本、产业配套、企业形象等多个维度综合评估，优先选择有扩展空间的园区。</p>
        </div>
        <div class="bg-white rounded-lg p-4 shadow-sm">
          <h3 class="font-semibold text-gray-900 mb-2">有哪些隐性成本需要注意？</h3>
          <p class="text-gray-600 text-sm">物业管理费、空调费、停车费、水电费、网络费等都可能另计，签约前务必确认全包价格。</p>
        </div>
      </div>
'''

    new_body = (
        f'\n        <div class="bg-{tag_color}-50 border-l-4 border-{tag_color}-500 p-4 mb-8 rounded">\n'
        f'          <p class="text-{tag_color}-900 font-medium">本文导览</p>\n'
        f'          <p class="text-sm text-{tag_color}-800 mt-1">{intro[:80]}...</p>\n'
        f'        </div>\n'
        f'\n        <p class="mb-4 text-gray-700 leading-relaxed">{intro}</p>\n'
        f'{sec_html}\n'
        f'{faq_html}'
    )
    return new_body

success = 0
fail = 0
missing = 0

for slug in remaining:
    if slug not in ARTICLES_DATA:
        missing += 1
        continue

    filepath = os.path.join(BLOG_DIR, f"{slug}.html")
    if not os.path.exists(filepath):
        print(f"MISS: {slug}")
        missing += 1
        continue

    data = ARTICLES_DATA[slug]
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    new_body = build_article_html(data['color'], data['tag'], data['intro'], data['sections'])

    # 替换正文内容
    start_marker = '<div class="prose max-w-none">'
    end_marker = '<div class="mt-12 pt-8 border-t">'
    s = content.find(start_marker)
    e = content.find(end_marker)

    if s == -1 or e == -1:
        print(f"MARKER MISS: {slug}")
        fail += 1
        continue

    new_content = content[:s+len(start_marker)] + new_body + content[e:]
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(new_content)
    print(f"OK: {slug}")
    success += 1

print(f"\nDone! Success: {success}, Fail: {fail}, Missing: {missing}")
